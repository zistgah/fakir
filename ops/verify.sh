#!/usr/bin/env bash
# ops/verify.sh — enforce ops/contract.json against this repository.
# Exits 0 only if every checkable invariant holds. This is the file to run first
# in a fresh session: one command, and you know the true state.
#   bash ops/verify.sh          # human output
#   bash ops/verify.sh --json   # machine output for another AI to consume
# © 1993–2026 Abhishek Choudhary. All rights reserved. AyeAI.
set -uo pipefail
cd "$(dirname "$0")/.."
JSON=0; [ "${1:-}" = "--json" ] && JSON=1
PASS=0; FAIL=0; RESULTS=""
rec(){ # id status detail
  if [ "$2" = PASS ]; then PASS=$((PASS+1)); else FAIL=$((FAIL+1)); fi
  RESULTS="${RESULTS}${1}|${2}|${3}"$'\n'
  [ "$JSON" = 1 ] || printf '  %s  %-22s %s\n' \
    "$([ "$2" = PASS ] && echo '  ok  ' || echo ' FAIL ')" "$1" "$3"
}

[ "$JSON" = 1 ] || echo "contract $(python3 -c 'import json;print(json.load(open("ops/contract.json"))["version"])' 2>/dev/null || echo '?') — $(git rev-parse --short HEAD)"

# C1 — manifest verifies
if [ ! -f MANIFEST.sha256 ]; then rec C1-manifest-verifies FAIL "MANIFEST.sha256 absent"
elif OUT="$(sha256sum -c MANIFEST.sha256 2>&1 | grep -v ': OK$')" && [ -n "$OUT" ]; then
  rec C1-manifest-verifies FAIL "$(printf '%s' "$OUT" | grep -c 'FAILED') failing: $(printf '%s' "$OUT" | grep 'FAILED' | head -3 | cut -d: -f1 | tr '\n' ' ')"
else rec C1-manifest-verifies PASS "$(grep -c . MANIFEST.sha256) files verify"; fi

# C2 — manifest covers every tracked file
if [ -f MANIFEST.sha256 ]; then
  MISS="$(comm -23 \
    <(git ls-files | grep -Ev '^MANIFEST\.sha256(\.ots)?$' | LC_ALL=C sort) \
    <(sed 's/^[0-9a-f]\{64\}  //' MANIFEST.sha256 | LC_ALL=C sort))"
  N="$(printf '%s' "$MISS" | grep -c . || true)"
  if [ "$N" -eq 0 ]; then rec C2-manifest-complete PASS "all tracked files covered"
  else rec C2-manifest-complete FAIL "$N absent, e.g. $(printf '%s' "$MISS" | head -3 | tr '\n' ' ')"; fi
fi

# C3 — a receipt for every substantive commit since Candor began.
# The boundary is DERIVED: the earliest commit that carries a receipt. Anything
# older predates the protocol and is exempt. No sha is hardcoded, so this stays
# true as history grows.
ATT="$(mktemp)"; for f in attest/receipts/*-PUSH.json; do [ -e "$f" ] || continue
  python3 - "$f" >> "$ATT" <<'PY'
import json,sys
try: print(json.load(open(sys.argv[1]))["subject"][0]["digest"]["gitCommit"])
except Exception: pass
PY
done
UNATT=""; SEEN_FIRST=0; EXEMPT=0
while read -r c; do
  [ -n "$c" ] || continue
  if grep -q "^$c$" "$ATT"; then SEEN_FIRST=1; continue; fi
  if [ "$SEEN_FIRST" = 0 ]; then EXEMPT=$((EXEMPT+1)); continue; fi   # older than the first receipt
  # Commits generated BY a gated operation are exempt: a seal attests the commit
  # before it, and a DOI record-back carries the digest it belongs to. Both name
  # their parent operation in the subject, so this is by declaration, not silence.
  case "$(git log -1 --format=%s "$c")" in
    attest:*|*"[Candor "*) continue ;;
  esac
  UNATT="$UNATT $(git rev-parse --short "$c")"
done < <(git rev-list --reverse HEAD)
rm -f "$ATT"
if [ -z "$UNATT" ]; then rec C3-receipt-per-commit PASS "attested from the first receipt onward ($EXEMPT older commits predate Candor)"
else rec C3-receipt-per-commit FAIL "unattested:$UNATT"; fi

# C4 — receipt schema
BAD=""
for f in attest/receipts/*.json; do [ -e "$f" ] || continue
  python3 - "$f" >/dev/null 2>&1 <<'PY' || BAD="$BAD $(basename "$f")"
import json,sys
d=json.load(open(sys.argv[1]))
assert d["_type"]=="https://in-toto.io/Statement/v1"
assert d["predicateType"]=="https://project-ilm.org/attestations/candor/v1"
assert d["subject"][0]["digest"]["gitCommit"]
p=d["predicate"]
assert p["action"] in ("PUSH","PAGES","MINT")
assert "reason" in p and p["utc"] and p["host"]
PY
done
[ -z "$BAD" ] && rec C4-receipt-schema PASS "$(ls -1 attest/receipts/*.json 2>/dev/null | wc -l) receipts conform" \
              || rec C4-receipt-schema FAIL "malformed:$BAD"

# C5 — archived manifests keep their proofs
ORPH=""
for m in attest/history/*-MANIFEST.sha256; do [ -e "$m" ] || continue
  [ -e "${m}.ots" ] || ORPH="$ORPH $(basename "$m")"
done
[ -z "$ORPH" ] && rec C5-proofs-immutable PASS "every archived manifest keeps its .ots" \
              || rec C5-proofs-immutable FAIL "proofless archives:$ORPH"

# C6 — copyright and affiliation
MISSC=""
for f in README.md CONTRACT.md index.html; do [ -e "$f" ] || continue
  grep -q '1993.\{0,3\}2026 Abhishek Choudhary' "$f" || MISSC="$MISSC $f"
done
BADAFF="$(grep -rlI 'Independent Researcher' --include='*.md' --include='*.json' --include='*.cff' . 2>/dev/null | grep -v '^./ops/contract.json' | head -3 | tr '\n' ' ')"
if [ -z "$MISSC" ] && [ -z "$BADAFF" ]; then rec C6-copyright PASS "line present; affiliation clean"
else rec C6-copyright FAIL "missing line:${MISSC:- none} · bad affiliation:${BADAFF:- none}"; fi

if [ "$JSON" = 1 ]; then
  python3 - "$PASS" "$FAIL" <<PY
import json,sys
rows=[l.split('|',2) for l in """$RESULTS""".strip().split("\n") if l]
print(json.dumps({"head":"$(git rev-parse --short HEAD)","pass":int(sys.argv[1]),
  "fail":int(sys.argv[2]),
  "checks":[{"id":a,"status":b,"detail":c} for a,b,c in rows]},indent=2))
PY
else
  echo
  if [ "$FAIL" -eq 0 ]; then echo "CONTRACT SATISFIED — $PASS checks"
  else echo "CONTRACT VIOLATED — $FAIL of $((PASS+FAIL)) checks failing"; fi
fi
[ "$FAIL" -eq 0 ]
